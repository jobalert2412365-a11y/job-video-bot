"""Run ONCE on your own computer to get a YouTube refresh token.
1. Put your downloaded OAuth file here as client_secret.json
2. python get_token.py  -> sign in -> copy the 3 printed values into GitHub secrets
"""
from google_auth_oauthlib.flow import InstalledAppFlow

flow = InstalledAppFlow.from_client_secrets_file(
    "client_secret.json", ["https://www.googleapis.com/auth/youtube.upload"])
creds = flow.run_local_server(port=0)
print("YT_CLIENT_ID     =", creds.client_id)
print("YT_CLIENT_SECRET =", creds.client_secret)
print("YT_REFRESH_TOKEN =", creds.refresh_token)
